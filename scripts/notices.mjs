// Writes public/third-party-notices.txt: the license text of every third-party package
// whose code or files ship in the built site. Run with `npm run notices` after adding
// or updating a dependency that ends up in the browser.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// What reaches the browser: the React app, its state library, the self-hosted fonts,
// and the Workbox runtime that vite-plugin-pwa bundles into the service worker.
const SHIPPED = [
  'react',
  'react-dom',
  'scheduler',
  'zustand',
  '@fontsource/instrument-serif',
  '@fontsource-variable/geist',
  'vite-plugin-pwa',
  'workbox-core',
  'workbox-precaching',
  'workbox-routing',
  'workbox-strategies',
  'workbox-expiration',
  'workbox-cacheable-response',
  'workbox-window',
];

const licenseText = (dir) => {
  const file = readdirSync(dir).find((f) => /^licen[cs]e(\.(md|txt))?$/i.test(f));
  return file ? readFileSync(join(dir, file), 'utf8').trim() : null;
};

const sections = SHIPPED.map((name) => {
  const dir = join('node_modules', name);
  if (!existsSync(dir)) throw new Error(`${name} is not installed; run npm install`);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const text = licenseText(dir);
  if (!text) throw new Error(`${name} has no license file`);
  return `${'='.repeat(78)}\n${pkg.name} ${pkg.version} (${pkg.license})\n${pkg.homepage ?? ''}\n${'='.repeat(78)}\n\n${text}\n`;
});

const header = `Whitenoise: third-party notices

Whitenoise itself is released under the MIT License (see LICENSE in the source
repository). It includes the following third-party software and fonts, each
under its own license, reproduced below.

All sounds are generated by Whitenoise's own code; no third-party recordings are
included.

`;

writeFileSync('public/third-party-notices.txt', header + sections.join('\n'));
console.log(`public/third-party-notices.txt: ${SHIPPED.length} packages`);
